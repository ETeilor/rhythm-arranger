def iv(g):                      # интервалы между ударами (расстояния) -> строка
    return ''.join('x' + '.' * (d - 1) for d in g)

def on(pos, n):                 # позиции ударов -> строка
    s = ['.'] * n
    for p in pos:
        s[p] = 'x'
    return ''.join(s)

def rot_eq(a, b):
    return len(a) == len(b) and b in a + a

def rot(s, k):
    k %= len(s)
    return s[k:] + s[:k]

def euclid(k, n):
    return ''.join('x' if (i * k) % n < k else '.' for i in range(n))

def vib(groups):                # скелет: x в начале каждой группы, остальное точки
    return iv(groups)

